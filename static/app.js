const $ = id => document.getElementById(id);
const signed = value => `${value >= 0 ? '+' : '−'}${Math.abs(value).toLocaleString('id-ID', {minimumFractionDigits: 3, maximumFractionDigits: 3})} dtk`;
const clock = value => new Date(value * 1000).toLocaleTimeString('id-ID', {hour12: false});
let busy = false;
async function request(path, data) {
  const response = await fetch(`/api/${path}`, data === undefined ? {} : {method: 'POST', headers: {'Content-Type': 'application/json'}, body: JSON.stringify(data)});
  const result = await response.json();
  if (!response.ok) throw new Error(result.error || 'Permintaan gagal');
  return result;
}
function render(state) {
  const online = state.nodes.filter(n => n.online);
  const offsets = [0, ...online.map(n => n.offset)];
  const spread = Math.max(...offsets) - Math.min(...offsets);
  $('status').textContent = `${online.length}/${state.nodes.length} client online`;
  $('spread').textContent = `${spread.toFixed(3)} detik`;
  const last = state.history.at(-1);
  $('round').textContent = String(last?.round || 0).padStart(2, '0');
  // Names are generated by the coordinator, never supplied by the user.
  const nodes = [{name: 'Koordinator', online: true, offset: 0, master: true}, ...state.nodes];
  $('clocks').innerHTML = nodes.map(n => `<article class="clock ${n.master ? 'master' : ''} ${!n.online ? 'offline' : ''}"><div class="clock-label">${n.name}<span class="chip">${n.master ? 'MASTER' : !n.online ? 'OFFLINE' : Math.abs(n.offset) > state.threshold ? 'OUTLIER' : 'CLIENT'}</span></div><time>${n.online ? clock(state.time + n.offset) : '— : — : —'}</time><small>${n.master ? 'Acuan pengukuran offset' : 'Selisih terhadap koordinator'}</small><div class="offset">${n.online ? signed(n.offset) : 'Tidak dapat dihubungi'}</div></article>`).join('');
  if (!last) {
    $('result-tag').textContent = 'Belum ada putaran';
    $('calculation').innerHTML = 'Klik <b>Sinkronkan sekarang</b> untuk mengumpulkan waktu dan menghitung koreksi.';
    $('rows').innerHTML = '<tr><td colspan="6">Hasil putaran terakhir akan muncul di sini.</td></tr>';
    return;
  }
  $('result-tag').textContent = `Putaran ${last.round} · ${last.count} jam dalam rata-rata`;
  const terms = ['0', ...last.nodes.filter(n => n.included).map(n => `(${n.offset.toFixed(3)})`)];
  $('calculation').textContent = `Rata-rata = [${terms.join(' + ')}] / ${last.count} = ${signed(last.average)}. Koreksi tiap client = rata-rata − offset client.`;
  $('rows').innerHTML = `<tr><td>Koordinator</td><td>0,000 dtk</td><td>—</td><td>Ya</td><td>${signed(last.average)}</td><td>Diterapkan lokal</td></tr>` + last.nodes.map(n => `<tr><td>${n.name}</td><td>${n.online ? signed(n.offset) : '—'}</td><td>${n.online ? (n.rtt * 1000).toFixed(2) + ' ms' : '—'}</td><td>${n.included ? 'Ya' : n.online ? 'Tidak · outlier' : 'Tidak · offline'}</td><td>${n.online ? signed(n.correction) : '—'}</td><td>${n.applied ? 'Berhasil' : n.online ? 'Gagal dikirim' : 'Dilewati'}</td></tr>`).join('');
}
async function refresh() {
  render(await request('state'));
}
async function action(kind) {
  if (busy) return;
  busy = true;
  $('sync').disabled = $('reset').disabled = true;
  $('message').textContent = kind === 'sync' ? 'Mengumpulkan jam → menghitung rata-rata → mengirim koreksi…' : 'Menerapkan skenario…';
  try {
    const result = await request(kind, {preset: $('preset').value});
    await refresh();
    const failed = kind === 'sync' ? result.nodes.filter(n => !n.applied).map(n => n.name) : result.failed;
    $('message').textContent = failed.length ? `Selesai dengan catatan: ${failed.join(', ')} tidak menerima perubahan.` : kind === 'sync' ? 'Sinkronisasi selesai. Bandingkan rentang selisih jam dan koreksi pada tabel.' : 'Skenario siap. Klik Sinkronkan sekarang untuk memulai.';
  } catch (error) { $('message').textContent = error.message; }
  finally { busy = false; $('sync').disabled = $('reset').disabled = false; }
}
$('sync').onclick = () => action('sync');
$('reset').onclick = () => action('reset');
async function poll() {
  if (!busy) {
    busy = true;
    try { await refresh(); }
    catch { $('status').textContent = 'Terputus'; $('message').textContent = 'Tidak dapat menghubungi server. Pastikan python app.py masih berjalan, lalu tunggu koneksi pulih.'; }
    finally { busy = false; }
  }
  setTimeout(poll, 2000);
}
$('message').textContent = 'Pilih skenario, lalu klik Sinkronkan sekarang. Jam di bawah adalah jam virtual.';
poll();
